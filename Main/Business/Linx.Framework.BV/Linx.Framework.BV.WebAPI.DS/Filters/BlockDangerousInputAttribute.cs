using System;
using System.Collections.Generic;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Text.RegularExpressions;
using System.Web.Http.Controllers;
using System.Web.Http.Filters;
using Newtonsoft.Json.Linq;

namespace Linx.Framework.BV.WebAPI.DS.Filters
{
    /// <summary>
    /// Edge guard for Web API actions: path traversal + soft query checks + optional SaveChanges payload walk.
    /// Does not replace parameterized SQL or HTML encoding on views.
    /// Register globally (preferred) or apply as [BlockDangerousInput] on a controller/action.
    /// </summary>
    [AttributeUsage(AttributeTargets.Class | AttributeTargets.Method, AllowMultiple = false, Inherited = true)]
    public class BlockDangerousInputAttribute : ActionFilterAttribute
    {
        public enum GuardMode
        {
            /// <summary>Only path-like parameters (reportPath, etc.).</summary>
            PathOnly = 0,
            /// <summary>Path checks + null-byte/length + obvious script markers on query values.</summary>
            Soft = 1
        }

        private static readonly string[] PathParameterNames =
        {
            "reportpath",
            "filepath",
            "templatepath",
            "path",
            "filename",
            "file"
        };

        private static readonly string[] SoftSkipParameterNames =
        {
            "authenticateparameters",
            "ticket",
            "mfaticket",
            "jentitysearch",
            "translatedjentitysearch",
            "jqueryexpression",
            "password",
            "senha",
            "secret",
            "authorizationtoken",
            "otpauthuri",
            "qrcodepngbase64"
        };

        /// <summary>Breeze / serializer metadata property names (case-insensitive).</summary>
        private static readonly HashSet<string> SavePayloadSkipPropertyNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "entityAspect",
            "entityType",
            "entityState",
            "entityKey",
            "originalValuesMap",
            "autoGeneratedKey",
            "extraMetadata",
            "$id",
            "$type",
            "$ref",
            "__unmapped",
            "complexAspect",
            "defaultResourceName",
            "namespace",
            "shortName",
            "dataProperties",
            "navigationProperties",
            "authenticateParameters",
            "ticket",
            "mfaTicket",
            "jEntitySearch",
            "translatedJEntitySearch",
            "jQueryExpression",
            "password",
            "senha",
            "secret",
            "authorizationToken",
            "otpauthUri",
            "qrCodePngBase64",
            "ACCESS_SECRET",
            "AccessSecret"
        };

        private static readonly Regex ObviousScriptPattern = new Regex(
            @"<\s*script\b|javascript\s*:|<\s*iframe\b|on\w+\s*=",
            RegexOptions.IgnoreCase | RegexOptions.CultureInvariant | RegexOptions.Compiled);

        public GuardMode Mode { get; set; }

        public int MaxQueryValueLength { get; set; }

        /// <summary>
        /// When true (default Soft), walk SaveChanges / JObject write payloads for business strings.
        /// </summary>
        public bool InspectSavePayload { get; set; }

        public int MaxSavePayloadStringLeaves { get; set; }

        public int MaxSavePayloadDepth { get; set; }

        public BlockDangerousInputAttribute()
        {
            Mode = GuardMode.Soft;
            MaxQueryValueLength = 32768;
            InspectSavePayload = true;
            MaxSavePayloadStringLeaves = 10000;
            MaxSavePayloadDepth = 64;
        }

        private const string RequestPropertyKey = "Linx.BlockDangerousInput.Validated";

        public override void OnActionExecuting(HttpActionContext actionContext)
        {
            if (actionContext == null)
                return;

            if (HasAllowDangerousInput(actionContext))
                return;

            // Avoid double work when registered globally and also applied as [BlockDangerousInput].
            if (actionContext.Request != null
                && actionContext.Request.Properties != null
                && actionContext.Request.Properties.ContainsKey(RequestPropertyKey))
                return;

            IEnumerable<KeyValuePair<string, string>> values = EnumerateIncomingValues(actionContext);
            foreach (KeyValuePair<string, string> pair in values)
            {
                string name = pair.Key ?? string.Empty;
                string value = pair.Value;
                if (string.IsNullOrEmpty(value))
                    continue;

                string nameKey = name.Trim().ToLowerInvariant();
                bool isPathParam = IsPathParameter(nameKey);

                string pathError;
                if (isPathParam && !IsSafePathValue(value, out pathError))
                {
                    Reject(actionContext, pathError);
                    return;
                }

                if (Mode == GuardMode.PathOnly)
                    continue;

                if (IsSoftSkipParameter(nameKey))
                    continue;

                string softError;
                if (!IsSoftSafeValue(value, out softError))
                {
                    Reject(actionContext, softError);
                    return;
                }
            }

            if (Mode != GuardMode.PathOnly && InspectSavePayload)
            {
                string payloadError;
                if (!TryValidateSavePayloads(actionContext, out payloadError))
                {
                    Reject(actionContext, payloadError);
                    return;
                }
            }

            if (actionContext.Request != null && actionContext.Request.Properties != null)
                actionContext.Request.Properties[RequestPropertyKey] = true;
        }

        private static bool HasAllowDangerousInput(HttpActionContext actionContext)
        {
            if (actionContext.ActionDescriptor != null
                && actionContext.ActionDescriptor.GetCustomAttributes<AllowDangerousInputAttribute>().Any())
                return true;

            if (actionContext.ControllerContext != null
                && actionContext.ControllerContext.ControllerDescriptor != null
                && actionContext.ControllerContext.ControllerDescriptor.GetCustomAttributes<AllowDangerousInputAttribute>().Any())
                return true;

            return false;
        }

        private static IEnumerable<KeyValuePair<string, string>> EnumerateIncomingValues(HttpActionContext actionContext)
        {
            var list = new List<KeyValuePair<string, string>>();

            if (actionContext.ActionArguments != null)
            {
                foreach (KeyValuePair<string, object> arg in actionContext.ActionArguments)
                {
                    if (arg.Value == null || arg.Value is byte[] || arg.Value is JToken)
                        continue;
                    Type t = arg.Value.GetType();
                    if (t.IsPrimitive || arg.Value is string || arg.Value is Guid || arg.Value is DateTime || arg.Value is decimal)
                        list.Add(new KeyValuePair<string, string>(arg.Key, Convert.ToString(arg.Value)));
                }
            }

            try
            {
                var query = actionContext.Request.GetQueryNameValuePairs();
                if (query != null)
                {
                    foreach (KeyValuePair<string, string> q in query)
                        list.Add(q);
                }
            }
            catch
            {
                // Ignore malformed query enumeration; action binding already failed or will fail.
            }

            return list;
        }

        private bool TryValidateSavePayloads(HttpActionContext actionContext, out string error)
        {
            error = null;
            if (actionContext.ActionArguments == null || actionContext.ActionArguments.Count == 0)
                return true;

            string actionName = actionContext.ActionDescriptor != null
                ? actionContext.ActionDescriptor.ActionName
                : null;

            foreach (KeyValuePair<string, object> arg in actionContext.ActionArguments)
            {
                JToken token = arg.Value as JToken;
                if (token == null)
                    continue;

                bool looksLikeSave =
                    string.Equals(actionName, "SaveChanges", StringComparison.OrdinalIgnoreCase)
                    || string.Equals(arg.Key, "saveBundle", StringComparison.OrdinalIgnoreCase)
                    || string.Equals(arg.Key, "changeSet", StringComparison.OrdinalIgnoreCase);

                // Only walk large JSON for known write shapes (avoid Excel/report POST bodies).
                if (!looksLikeSave)
                    continue;

                string pathHit;
                int leafCount = 0;
                if (!TryWalkBusinessStrings(token, arg.Key ?? "body", 0, ref leafCount, out pathHit, out error))
                {
                    if (string.IsNullOrEmpty(error))
                        error = "Payload de gravação rejeitado pelo filtro de segurança.";
                    else if (!string.IsNullOrEmpty(pathHit))
                        error = error + " Campo: " + pathHit + ".";
                    return false;
                }
            }

            return true;
        }

        private bool TryWalkBusinessStrings(JToken token, string path, int depth, ref int leafCount, out string pathHit, out string error)
        {
            pathHit = null;
            error = null;

            if (token == null || token.Type == JTokenType.Null || token.Type == JTokenType.Undefined)
                return true;

            if (depth > MaxSavePayloadDepth)
            {
                error = "Payload de gravação excede a profundidade máxima permitida.";
                pathHit = path;
                return false;
            }

            if (token.Type == JTokenType.String)
            {
                string value = token.Value<string>();
                if (string.IsNullOrEmpty(value))
                    return true;

                string leafName = path;
                int lastDot = path.LastIndexOf('.');
                int lastBracket = path.LastIndexOf('[');
                if (lastDot >= 0 && lastDot > lastBracket)
                    leafName = path.Substring(lastDot + 1);
                else if (lastBracket < 0)
                    leafName = path;

                if (IsSoftSkipParameter(leafName.ToLowerInvariant()) || SavePayloadSkipPropertyNames.Contains(leafName))
                    return true;

                leafCount++;
                if (leafCount > MaxSavePayloadStringLeaves)
                {
                    error = "Payload de gravação excede o número máximo de campos de texto.";
                    pathHit = path;
                    return false;
                }

                string softError;
                if (!IsSoftSafeValue(value, out softError))
                {
                    error = softError;
                    pathHit = path;
                    return false;
                }
                return true;
            }

            JObject obj = token as JObject;
            if (obj != null)
            {
                foreach (JProperty prop in obj.Properties())
                {
                    if (SavePayloadSkipPropertyNames.Contains(prop.Name) || IsSoftSkipParameter(prop.Name.ToLowerInvariant()))
                        continue;

                    string childPath = string.IsNullOrEmpty(path) ? prop.Name : path + "." + prop.Name;
                    if (!TryWalkBusinessStrings(prop.Value, childPath, depth + 1, ref leafCount, out pathHit, out error))
                        return false;
                }
                return true;
            }

            JArray arr = token as JArray;
            if (arr != null)
            {
                for (int i = 0; i < arr.Count; i++)
                {
                    string childPath = path + "[" + i.ToString() + "]";
                    if (!TryWalkBusinessStrings(arr[i], childPath, depth + 1, ref leafCount, out pathHit, out error))
                        return false;
                }
                return true;
            }

            return true;
        }

        private static bool IsPathParameter(string nameKey)
        {
            for (int i = 0; i < PathParameterNames.Length; i++)
            {
                if (nameKey == PathParameterNames[i] || nameKey.EndsWith(PathParameterNames[i], StringComparison.Ordinal))
                    return true;
            }
            return false;
        }

        private static bool IsSoftSkipParameter(string nameKey)
        {
            for (int i = 0; i < SoftSkipParameterNames.Length; i++)
            {
                if (nameKey == SoftSkipParameterNames[i])
                    return true;
            }
            return false;
        }

        internal static bool IsSafePathValue(string value, out string error)
        {
            error = null;
            if (string.IsNullOrWhiteSpace(value))
            {
                error = "Caminho de arquivo vazio.";
                return false;
            }

            string decoded = Uri.UnescapeDataString(value.Replace('+', ' '));
            if (decoded.IndexOf('\0') >= 0)
            {
                error = "Caminho de arquivo inválido (null byte).";
                return false;
            }

            string normalized = decoded.Replace('/', '\\');
            if (normalized.IndexOf("..", StringComparison.Ordinal) >= 0)
            {
                error = "Caminho de arquivo inválido (path traversal).";
                return false;
            }

            if (normalized.StartsWith("\\", StringComparison.Ordinal)
                || Regex.IsMatch(normalized, @"^[A-Za-z]:\\"))
            {
                error = "Caminho de arquivo absoluto não permitido.";
                return false;
            }

            if (normalized.IndexOf(':') >= 0)
            {
                error = "Caminho de arquivo inválido.";
                return false;
            }

            return true;
        }

        private bool IsSoftSafeValue(string value, out string error)
        {
            error = null;
            if (value.IndexOf('\0') >= 0)
            {
                error = "Entrada inválida (null byte).";
                return false;
            }

            if (MaxQueryValueLength > 0 && value.Length > MaxQueryValueLength)
            {
                error = "Entrada excede o tamanho máximo permitido.";
                return false;
            }

            if (ObviousScriptPattern.IsMatch(value))
            {
                error = "Entrada contém marcadores de script/HTML não permitidos.";
                return false;
            }

            return true;
        }

        private static void Reject(HttpActionContext actionContext, string message)
        {
            actionContext.Response = actionContext.Request.CreateErrorResponse(
                HttpStatusCode.BadRequest,
                string.IsNullOrWhiteSpace(message) ? "Entrada rejeitada pelo filtro de segurança." : message);
        }
    }
}
