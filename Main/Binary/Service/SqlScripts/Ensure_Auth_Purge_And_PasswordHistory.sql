-- ENTERMODA-44977: create purge-control + password-history tables (idempotent).
-- Target: same database as FrameworkAutorizacao / aspnet_Membership / TCS_LOG_ACESSO_AUTH.
-- The Service also auto-creates these on any auth-access EnsureAuthAccessTable() call after deploy.

IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = N'LX_TCS')
    EXEC(N'CREATE SCHEMA [LX_TCS]');
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.tables t
    INNER JOIN sys.schemas s ON t.schema_id = s.schema_id
    WHERE s.name = N'LX_TCS' AND t.name = N'TCS_CONTROLE_EXPURGO_AUDITORIA')
BEGIN
    CREATE TABLE [LX_TCS].[TCS_CONTROLE_EXPURGO_AUDITORIA]
    (
        [PROCESSO] NVARCHAR(64) NOT NULL,
        [DATA_ULTIMO_EXPURGO] DATETIME NULL,
        [OBSERVACAO] NVARCHAR(500) NULL,
        CONSTRAINT [XPK_TCS_CONTROLE_EXPURGO_AUDITORIA] PRIMARY KEY CLUSTERED ([PROCESSO] ASC)
    );
END
GO

IF NOT EXISTS (
    SELECT 1 FROM [LX_TCS].[TCS_CONTROLE_EXPURGO_AUDITORIA]
    WHERE [PROCESSO] = N'AUDITORIA_LOGIN')
BEGIN
    INSERT INTO [LX_TCS].[TCS_CONTROLE_EXPURGO_AUDITORIA] ([PROCESSO], [DATA_ULTIMO_EXPURGO], [OBSERVACAO])
    VALUES (N'AUDITORIA_LOGIN', NULL, N'Controle inicial (ainda sem expurgo)');
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.tables t
    INNER JOIN sys.schemas s ON t.schema_id = s.schema_id
    WHERE s.name = N'LX_TCS' AND t.name = N'TCS_HISTORICO_SENHA_USUARIO')
BEGIN
    CREATE TABLE [LX_TCS].[TCS_HISTORICO_SENHA_USUARIO]
    (
        [ID_TCS_HISTORICO_SENHA_USUARIO] INT IDENTITY(1,1) NOT NULL,
        [NOME_USUARIO] NVARCHAR(256) NOT NULL,
        [PASSWORD_HASH] NVARCHAR(128) NOT NULL,
        [PASSWORD_SALT] NVARCHAR(128) NOT NULL,
        [PASSWORD_FORMAT] INT NOT NULL CONSTRAINT [DF_TCS_HISTORICO_SENHA_FORMAT] DEFAULT ((1)),
        [DATA_ALTERACAO] DATETIME NOT NULL CONSTRAINT [DF_TCS_HISTORICO_SENHA_DATA] DEFAULT (GETDATE()),
        CONSTRAINT [XPK_TCS_HISTORICO_SENHA_USUARIO] PRIMARY KEY CLUSTERED ([ID_TCS_HISTORICO_SENHA_USUARIO] ASC)
    );
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'IX_TCS_HISTORICO_SENHA_USUARIO_NOME_DATA'
      AND object_id = OBJECT_ID(N'LX_TCS.TCS_HISTORICO_SENHA_USUARIO'))
BEGIN
    CREATE NONCLUSTERED INDEX [IX_TCS_HISTORICO_SENHA_USUARIO_NOME_DATA]
        ON [LX_TCS].[TCS_HISTORICO_SENHA_USUARIO] ([NOME_USUARIO], [DATA_ALTERACAO] DESC);
END
GO

