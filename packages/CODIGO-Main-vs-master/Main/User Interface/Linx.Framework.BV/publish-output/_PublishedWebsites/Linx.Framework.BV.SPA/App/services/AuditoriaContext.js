     var finalizeAllLookUpTcsUsuario = function (replaceTo, selectedElements, propertyName, lookupInfo) {
        if (!replaceTo || !selectedElements)
            return;
        if (!Array.isArray(selectedElements)) {
            selectedElements = [selectedElements];
        }
        isFinalizingLookup(true);
        if (!propertyName)
            propertyName = '';
        var isUsedOriginalRow = false;
        for (var i = 0; i < selectedElements.length; i++)
        {
            var selectedElement = selectedElements[i];
            if (propertyName === '' || propertyName === 'Email') {
               if (selectedElement.hasOwnProperty('Email') && replaceTo.hasOwnProperty('Email'))
               {
                   setAbsoluteValue(replaceTo, 'Email', getAbsoluteValue(selectedElement['Email']));
               }
               else if (replaceTo.hasOwnProperty('Email')) {
                   setAbsoluteValue(replaceTo, 'Email', null);
               }
            }
            if (propertyName === '' || propertyName === 'IdUsuario') {
               if (selectedElement.hasOwnProperty('IdUsuario') && replaceTo.hasOwnProperty('IdUsuario'))
               {
                   setAbsoluteValue(replaceTo, 'IdUsuario', getAbsoluteValue(selectedElement['IdUsuario']));
               }
               else if (replaceTo.hasOwnProperty('IdUsuario')) {
                   setAbsoluteValue(replaceTo, 'IdUsuario', 0);
               }
            }
            if (propertyName === '' || propertyName === 'NomeUsuario') {
               if (selectedElement.hasOwnProperty('NomeUsuario') && replaceTo.hasOwnProperty('NomeUsuario'))
               {
                   setAbsoluteValue(replaceTo, 'NomeUsuario', getAbsoluteValue(selectedElement['NomeUsuario']));
               }
               else if (replaceTo.hasOwnProperty('NomeUsuario')) {
                   setAbsoluteValue(replaceTo, 'NomeUsuario', '');
               }
            }
            if (replaceTo.validatedlookupsArray && !replaceTo.validatedlookupsArray.contains('LookUpTcsUsuario'))
                replaceTo.validatedlookupsArray.push('LookUpTcsUsuario');
        }
        //Trigger context data update event
        if (replaceTo.isPOCO) vm.refreshCurrentBind();
        document.dispatchEvent(dataUpdateEvent);
        isFinalizingLookup(false);
    };
    
