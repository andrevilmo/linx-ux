     var finalizeAllLookUpTcsConexaoDb = function (replaceTo, selectedElements, propertyName, lookupInfo) {
        if (!replaceTo || !selectedElements)
            return;
        if (!Array.isArray(selectedElements)) {
            selectedElements = [selectedElements];
        }
        var originalRow = replaceTo;
        var hasDisconsideredElement = false;
        var parent = getAbsoluteValue(replaceTo.TcsAplicativo);
        isFinalizingLookup(true);
        if (!propertyName)
            propertyName = '';
        var isUsedOriginalRow = false;
        for (var i = 0; i < selectedElements.length; i++)
        {
            var selectedElement = selectedElements[i];
            var isInvalidElement = false;
            var curList = parent.TcsAplicativoConexaoList();
            for (var idx = 0; idx < curList.length; idx++) {
               if (curList[idx] != originalRow && getAbsoluteValue(curList[idx].IdConexaoDb) === getAbsoluteValue(selectedElement['IdConexaoDb'])) {
                   isInvalidElement = true;
                   hasDisconsideredElement = true;
                   break;
               }
            }
            if (isInvalidElement) continue;
            if (isUsedOriginalRow) {
                replaceTo = lookupInfo.vm.createTcsAplicativoConexao(parent);
            }
            else {
                isUsedOriginalRow = true;
            }
            if (propertyName === '' || propertyName === 'IdConexaoDb') {
               if (selectedElement.hasOwnProperty('IdConexaoDb') && replaceTo.hasOwnProperty('IdConexaoDb'))
               {
                   setAbsoluteValue(replaceTo, 'IdConexaoDb', getAbsoluteValue(selectedElement['IdConexaoDb']));
               }
               else if (replaceTo.hasOwnProperty('IdConexaoDb')) {
                   setAbsoluteValue(replaceTo, 'IdConexaoDb', 0);
               }
            }
            if (propertyName === '' || propertyName === 'NomeConexao') {
               if (selectedElement.hasOwnProperty('NomeConexao') && replaceTo.hasOwnProperty('NomeConexao'))
               {
                   setAbsoluteValue(replaceTo, 'NomeConexao', getAbsoluteValue(selectedElement['NomeConexao']));
               }
               else if (replaceTo.hasOwnProperty('NomeConexao')) {
                   setAbsoluteValue(replaceTo, 'NomeConexao', '');
               }
            }
            if (replaceTo.validatedlookupsArray && !replaceTo.validatedlookupsArray.contains('LookUpTcsConexaoDb'))
                replaceTo.validatedlookupsArray.push('LookUpTcsConexaoDb');
        }
        //Trigger context data update event
        if (replaceTo.isPOCO) vm.refreshCurrentBind();
        document.dispatchEvent(dataUpdateEvent);
        isFinalizingLookup(false);
        if (hasDisconsideredElement) {
           clearLookUpTcsConexaoDb(replaceTo);
           app.showMessage('Itens que já estão sendo utilizados foram desconsiderados nessa seleção!', 'Informação', ['Ok']);
        }
    };
    
